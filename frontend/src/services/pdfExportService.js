        probability: 'Olasılık',
        disclaimer: 'Tıbbi Sorumluluk Reddi',
        disclaimerText: 'Bu rapor bir yapay zeka tanı aracı tarafından oluşturulmuştur ve kesin bir teşhis olarak kabul edilmemelidir. Tüm bulgular nitelikli bir tıbbi uzman tarafından gözden geçirilmeli ve doğrulanmalıdır. Bu araç, klinisyenlerin tanı sürecine yardımcı olmak için tasarlanmıştır, klinik yargıyı değiştirmez.',
