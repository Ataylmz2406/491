  /**
   * Export HTML to PDF using browser's print functionality as fallback
   * or html2pdf if available
   */
  static async _exportToPDF(element, filename) {
    // Try using html2pdf library if available
    if (window.html2pdf) {
      const opt = {
        margin: 10,
        filename: filename,
        image: { type: 'jpeg', quality: 0.98 },
        html2canvas: { scale: 2 },
        jsPDF: { orientation: 'portrait', unit: 'mm', format: 'a4' },
      };
      window.html2pdf().set(opt).from(element).save();
    } else {
      // Fallback: Use print dialog
      const printWindow = window.open('', '', 'height=600,width=800');
      printWindow.document.write(`
        <html>
          <head>
            <title>${filename}</title>
            <style>
              ${element.style.cssText}
              body { margin: 20px; }
            </style>
          </head>
          <body>
            ${element.innerHTML}
          </body>
        </html>
      `);
      printWindow.document.close();
      printWindow.print();
    }
  }

